const STORAGE_KEY = "samatkaarEnglishAcademyV1";
const readSaved = () => {
  try {
    const raw = JSON.parse(localStorage.getItem(STORAGE_KEY) || "{}");
    return { done: Array.isArray(raw.done) ? raw.done : [], bookmarked: Array.isArray(raw.bookmarked) ? raw.bookmarked : [], current: Number.isInteger(raw.current) ? Math.max(0, Math.min(999, raw.current)) : 0 };
  } catch { return { done: [], bookmarked: [], current: 0 }; }
};
function shuffle(items) {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
function normalize(text) { return text.toLowerCase().replace(/[^a-z0-9 ]/g, "").replace(/\s+/g, " ").trim(); }
function createQuiz(step) {
  const other = STEPS.filter(s => s.course === step.course && s.unit !== step.unit && s.mode === step.mode);
  const distractors = shuffle(other).slice(0, 3);
  const choices = shuffle([step, ...distractors]);
  const tokens = step.en.replace(/[.!?]/g, "").split(/\s+/);
  const blankIndex = tokens.length > 2 ? Math.floor(tokens.length / 2) : 0;
  return { choices, tokens, blankIndex, shuffledTokens: shuffle(tokens.map((word, i) => ({ word, i }))) };
}
function SpeechButton({ text, label = "🔊 Listen" }) {
  const [speaking, setSpeaking] = useState(false);
  const speak = () => {
    if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = "en-US";
    utterance.rate = 0.82;
    utterance.onend = () => setSpeaking(false);
    utterance.onerror = () => setSpeaking(false);
    setSpeaking(true);
    window.speechSynthesis.speak(utterance);
  };
  return <button type="button" onClick={speak} style={{ ...baseButton, color: COLORS.blue, background: "#eff6ff" }}>{speaking ? "🔊 Playing..." : label}</button>;
}
